#!/usr/bin/env python3
"""
Build the WordCore program for one or more targets.

    python runtime/build/build.py                 # all targets
    python runtime/build/build.py linux-x86_64    # one target
    python runtime/build/build.py --list

Needs Python 3.8+ and Zig (as the C cross-compiler):  pip install ziglang==0.15.2
Output: dist/<target>/wordcore[.exe]

The Lua files in core/ are embedded into the program, so the result is one file.
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNTIME = ROOT / "runtime"
VENDOR = RUNTIME / "vendor"
SRC = RUNTIME / "src"
CORE = ROOT / "core"
WORK = ROOT / "build"
DIST = ROOT / "dist"

TARGETS = {
    "linux-x86_64":  {"zig": "x86_64-linux-musl",   "os": "linux"},
    "linux-arm64":   {"zig": "aarch64-linux-musl",  "os": "linux"},
    "windows-x64":   {"zig": "x86_64-windows-gnu",  "os": "windows"},
    "macos-arm64":   {"zig": "aarch64-macos",       "os": "macos"},
    "macos-x64":     {"zig": "x86_64-macos",        "os": "macos"},
}

LUA_SOURCES = [
    "lapi.c", "lauxlib.c", "lbaselib.c", "lcode.c", "lcorolib.c", "lctype.c", "ldblib.c",
    "ldebug.c", "ldo.c", "ldump.c", "lfunc.c", "lgc.c", "linit.c", "liolib.c", "llex.c",
    "lmathlib.c", "lmem.c", "loadlib.c", "lobject.c", "lopcodes.c", "loslib.c", "lparser.c",
    "lstate.c", "lstring.c", "lstrlib.c", "ltable.c", "ltablib.c", "ltm.c", "lundump.c",
    "lutf8lib.c", "lvm.c", "lzio.c",
]

SQLITE_DEFINES = [
    "SQLITE_DQS=0",
    "SQLITE_DEFAULT_FOREIGN_KEYS=1",
    "SQLITE_DEFAULT_MEMSTATUS=0",
    "SQLITE_DEFAULT_WAL_SYNCHRONOUS=1",
    "SQLITE_LIKE_DOESNT_MATCH_BLOBS",
    "SQLITE_OMIT_DEPRECATED",
    "SQLITE_OMIT_LOAD_EXTENSION",
    "SQLITE_OMIT_SHARED_CACHE",
    "SQLITE_ENABLE_FTS5",
    "SQLITE_ENABLE_MATH_FUNCTIONS",
    "SQLITE_THREADSAFE=1",
]


def zig_cc():
    zig = shutil.which("zig")
    if zig:
        return [zig, "cc"]
    try:
        import ziglang  # noqa: F401
    except ImportError:
        sys.exit("Zig not found. Install it with:  pip install ziglang==0.15.2")
    return [sys.executable, "-m", "ziglang", "cc"]


def version():
    v = (RUNTIME / "VERSION").read_text().strip()
    try:
        rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT,
                               capture_output=True, text=True).stdout.strip()
        v += f"+{rev}" + ("-dirty" if dirty else "")
    except Exception:
        pass
    return v


def build_luac(cc):
    """A small host program that turns Lua source into bytecode (see wcluac.c)."""
    exe = WORK / "host" / ("wcluac.exe" if os.name == "nt" else "wcluac")
    srcs = [VENDOR / "lua" / f for f in LUA_SOURCES if f not in ("lua.c", "luac.c")] + [RUNTIME / "build" / "wcluac.c"]
    h = hashlib.sha256()
    for f in srcs:
        h.update(f.read_bytes())
    stamp = exe.with_suffix(".stamp")
    if exe.exists() and stamp.exists() and stamp.read_text() == h.hexdigest():
        return exe
    exe.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run(cc + ["-O1", "-std=gnu11", "-w", f"-I{VENDOR / 'lua'}", "-o", str(exe)] + [str(f) for f in srcs] + ["-lm"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        sys.exit("could not build the bytecode helper")
    stamp.write_text(h.hexdigest())
    return exe


def precompile(luac, name, p: Path):
    """Bytecode for a core .lua file (loads ~7x faster than source: matters for CGI)."""
    out = WORK / "bytecode" / (name + "c")
    out.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([str(luac), "@" + name, str(p), str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"Lua error in {name}: {r.stderr.strip()}")
    return out.read_bytes()


def generate_embedded(out: Path, luac=None):
    """Write a C file containing every core file as a byte array (Lua as bytecode)."""
    files = sorted(p for p in CORE.rglob("*") if p.is_file() and p.name != "README.md")
    lines = ['/* Generated by runtime/build/build.py — do not edit. */',
             '#include "wc_native.h"', '']
    entries = []
    extra = [("core/NOTICES.txt", RUNTIME / "vendor" / "NOTICES.txt")]
    named = [("core/" + p.relative_to(CORE).as_posix(), p) for p in files] + extra
    for i, (name, p) in enumerate(named):
        data = precompile(luac, name, p) if (luac and name.endswith(".lua")) else p.read_bytes()
        hexed = ",".join(str(b) for b in data)
        lines.append(f"static const unsigned char f{i}[] = {{{hexed},0}};")
        entries.append(f'  {{"{name}", f{i}, {len(data)}UL}},')
    lines.append("const wc_embedded_file wc_embedded_files[] = {")
    lines.extend(entries)
    lines.append('  {0, 0, 0}')
    lines.append("};")
    lines.append(f"const unsigned long wc_embedded_count = {len(named)}UL;")
    content = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text() != content:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content)
    return len(named)


def compile_obj(cc, target, src: Path, obj: Path, flags):
    """Compile one C file, skipping it when source and flags are unchanged."""
    h = hashlib.sha256(src.read_bytes() + " ".join(flags).encode() + target["zig"].encode())
    if src.parent == SRC or src.name == "embedded.c":
        for hdr in sorted(SRC.glob("*.h")):
            h.update(hdr.read_bytes())
    stamp = h.hexdigest()
    stampfile = obj.with_suffix(".stamp")
    if obj.exists() and stampfile.exists() and stampfile.read_text() == stamp:
        return
    obj.parent.mkdir(parents=True, exist_ok=True)
    cmd = cc + ["-target", target["zig"], "-c", str(src), "-o", str(obj)] + flags
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        sys.exit(f"compile failed: {src.name} for {target['zig']}")
    if r.stderr.strip():
        sys.stderr.write(r.stderr)
    stampfile.write_text(stamp)


def build_target(name, cc, ver, embedded_c):
    t = TARGETS[name]
    objdir = WORK / "obj" / name
    base = ["-O2", "-std=gnu11", "-fno-sanitize=undefined", f'-DWC_VERSION="{ver}"',
            f"-I{VENDOR / 'lua'}", f"-I{VENDOR / 'sqlite'}", f"-I{VENDOR / 'monocypher'}", f"-I{VENDOR / 'cmark-gfm'}", f"-I{SRC}"]
    if t["os"] in ("linux", "macos"):
        base.append("-DLUA_USE_POSIX")   # POSIX goodies, but no dlopen: addons are Lua only

    objs = []
    for f in LUA_SOURCES:
        o = objdir / "lua" / (f[:-2] + ".o")
        compile_obj(cc, t, VENDOR / "lua" / f, o, base)
        objs.append(o)
    o = objdir / "sqlite3.o"
    compile_obj(cc, t, VENDOR / "sqlite" / "sqlite3.c", o, base + [f"-D{d}" for d in SQLITE_DEFINES])
    objs.append(o)
    o = objdir / "monocypher.o"
    compile_obj(cc, t, VENDOR / "monocypher" / "monocypher.c", o, base)
    objs.append(o)
    for f in sorted(p.name for p in (VENDOR / "cmark-gfm").glob("*.c")):
        o = objdir / "cmark" / (f[:-2] + ".o")
        compile_obj(cc, t, VENDOR / "cmark-gfm" / f, o, base + ["-DCMARK_GFM_STATIC_DEFINE", "-DCMARK_GFM_EXTENSIONS_STATIC_DEFINE", "-w"])
        objs.append(o)
    for f in ["main.c", "wc_native.c", "wc_sqlite.c", "wc_crypto.c", "wc_markdown.c"]:
        o = objdir / (f[:-2] + ".o")
        compile_obj(cc, t, SRC / f, o, base + ["-Wall", "-Wextra", "-Wno-unused-parameter"])
        objs.append(o)
    o = objdir / "embedded.o"
    compile_obj(cc, t, embedded_c, o, base)
    objs.append(o)

    exe = "wordcore.exe" if t["os"] == "windows" else "wordcore"
    out = DIST / name / exe
    out.parent.mkdir(parents=True, exist_ok=True)
    link = cc + ["-target", t["zig"], "-o", str(out)] + [str(x) for x in objs]
    if t["os"] == "linux":
        link += ["-static", "-s", "-lm"]
    elif t["os"] == "windows":
        link += ["-s", "-lws2_32", "-lbcrypt"]
    elif t["os"] == "macos":
        link += ["-s"]
    r = subprocess.run(link, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        sys.exit(f"link failed for {name}")
    for junk in out.parent.glob("*.pdb"):
        junk.unlink()
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("targets", nargs="*", help="targets to build (default: all)")
    ap.add_argument("--list", action="store_true", help="list targets")
    args = ap.parse_args()
    if args.list:
        print("\n".join(TARGETS))
        return
    names = args.targets or list(TARGETS)
    for n in names:
        if n not in TARGETS:
            sys.exit(f"unknown target {n!r}; use --list")

    cc = zig_cc()
    ver = version()
    embedded_c = WORK / "gen" / "embedded.c"
    count = generate_embedded(embedded_c, build_luac(cc))
    print(f"WordCore {ver} — {count} core files embedded")
    for n in names:
        t0 = time.time()
        out = build_target(n, cc, ver, embedded_c)
        print(f"  {n:<14} {out.relative_to(ROOT)}  {out.stat().st_size / 1e6:.1f} MB  ({time.time() - t0:.0f}s)")


if __name__ == "__main__":
    main()
